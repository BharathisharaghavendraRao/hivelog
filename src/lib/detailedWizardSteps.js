export function emptyDetailedForm(hive) {
  const blank = Object.fromEntries(
    DETAILED_WIZARD_STEPS.map((step) => [step.field, '']),
  )
  return {
    ...blank,
    inspectionDate: todayLabel(),
    inspectionTime: nowTimeLabel(),
    hiveName: hive?.name ?? '',
    yard: hive?.location ?? '',
    location: hive?.location ?? '',
  }
}

export function buildDetailedQuestionSpeech(step, stepIndex) {
  const num = stepIndex + 1
  const total = DETAILED_WIZARD_STEPS.length
  const suggestions =
    step.type === 'multi'
      ? ` Select all that apply: ${step.options.join(', ')}. Then say next.`
      : step.options?.length
        ? ` Options: ${step.options.join(', ')}.`
        : ' Answer in your own words, then say next.'
  return `Detailed inspection. Question ${num} of ${total}. ${step.section}. ${step.question}${suggestions}`
}

export function buildDetailedConfirmation(step, value) {
  if (value) return `${step.title}: ${value}.`
  return `${step.title} skipped.`
}

